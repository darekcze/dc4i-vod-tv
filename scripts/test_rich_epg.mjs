import assert from 'node:assert/strict';
import {existsSync,readFileSync} from 'node:fs';
import vm from 'node:vm';
import {execFileSync} from 'node:child_process';
const context={window:{},Date,JSON,Number,String,Array,Object,Math};
if(existsSync('src/vod-rich-epg.js'))vm.runInNewContext(readFileSync('src/vod-rich-epg.js','utf8'),context);
const epg=context.window.DC4IRichEpg;
assert.ok(epg,'rich EPG API must exist');
let now=1792890000000;
const snapshot=JSON.parse(execFileSync('python3',['scripts/xmltv_metadata.py','tests/fixtures/epg/synthetic.xml','--source','synthetic-test','--fetched-at',String(now)],{encoding:'utf8'}));
const copy=x=>JSON.parse(JSON.stringify(x));
const channels=snapshot.channels;
assert.equal(epg.mapChannel({epg_channel_id:'synthetic.one',title:'Wrong title'},channels).channelId,'synthetic.one');
assert.equal(epg.mapChannel({epg_channel_id:'missing',title:'Żółć TV HD'},channels).status,'unmapped');
assert.equal(epg.mapChannel({title:'  ZOLC   tv hd '},channels).status,'suggested');
assert.equal(epg.mapChannel({title:'Żółć TV'},channels).status,'unmapped','HD distinctions retained');
assert.equal(epg.mapChannel({title:'Żółć TV HD'},[...channels,{id:'duplicate',names:['Żółć TV HD']}]).status,'ambiguous');
assert.equal(epg.mapChannel({epg_channel_id:'synthetic.one'},[...channels,channels[0]]).status,'ambiguous');
assert.equal(epg.mapChannel({title:'alias'},[{id:'a',names:['Original','Alias']},null]).channelId,'a');
const timeline=epg.timeline(snapshot,'synthetic.one',1792886400000,1792900000000);
assert.deepEqual(Array.from(timeline,e=>e.title),['Pierwsza godzina','Druga godzina']);
assert.ok(timeline.every(e=>e.playable===false&&e.tracks.audio==='unknown'&&e.rating?.verified!==true));
assert.throws(()=>epg.timeline(snapshot,'synthetic.one',0,11*86400000),/window/);
assert.equal(epg.timeline(snapshot,'synthetic.one',1792889400000,1792891800000).length,0,'half-open overlap');

const cache=epg.createCache({now:()=>now,ttlMs:1000,staleMs:2000,maxSources:2});
const valid=copy(snapshot);valid.diagnostics.skipped=0;
assert.equal(cache.put(valid).accepted,true);
valid.events[0].title='caller mutation';
let read=cache.get('synthetic-test');
assert.equal(read.status,'fresh');assert.equal(read.snapshot.events[0].title,'Pierwsza godzina');
read.snapshot.events[0].title='read mutation';
assert.equal(cache.get('synthetic-test').snapshot.events[0].title,'Pierwsza godzina');
const partial=copy(snapshot);partial.fetchedAt=now+100;now+=100;
assert.equal(cache.put(partial).reason,'partial','do not erase a previous snapshot with partial feed');
now+=900;assert.equal(cache.get('synthetic-test').status,'stale','expiry uses original fetch time');
assert.equal(cache.put({...copy(valid),fetchedAt:now+1}).reason,'future');
assert.equal(cache.put({...copy(valid),fetchedAt:now-1001}).reason,'older');
assert.equal(cache.put({...copy(valid),schemaVersion:99}).reason,'invalid');
assert.equal(cache.put({...copy(valid),source:'https://host/?password=secret'}).reason,'invalid');
now+=2000;assert.equal(cache.get('synthetic-test').status,'missing','bounded stale eviction');
assert.equal(cache.put({...copy(snapshot),fetchedAt:now}).accepted,true);
assert.equal(cache.get('synthetic-test').partial,true,'initial partial explicitly labeled');
for(const source of ['second','third'])assert.equal(cache.put({...copy(valid),source,fetchedAt:now}).accepted,true);
assert.equal(cache.get('synthetic-test').status,'missing','source count bounded');
cache.clear();assert.equal(cache.get('third').status,'missing');
assert.throws(()=>epg.createCache({ttlMs:0}),/limits/);
assert.equal(cache.put({...copy(valid),events:Array(20001).fill(valid.events[0])}).reason,'invalid');

const clean=copy(valid);clean.fetchedAt=now;clean.password='do-not-copy';
clean.events[0].streamUrl='https://private.invalid/password';clean.events[0].tmdb={id:123};
clean.events.push(copy(clean.events[0]));
assert.equal(cache.put(clean).accepted,true);
const serialized=JSON.stringify(cache.get('synthetic-test'));
assert.ok(!serialized.includes('password')&&!serialized.includes('private.invalid')&&!serialized.includes('tmdb'));
assert.equal(cache.get('synthetic-test').snapshot.events.length,3,'duplicate event collapsed');
console.log('RICH_EPG_PASS identity/ambiguity, provenance, DST, partial/stale TTL, ordering, limits, isolation');
