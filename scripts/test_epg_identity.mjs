import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import vm from 'node:vm';
const ctx={window:{}};
if(existsSync('src/vod-epg-identity.js'))vm.runInNewContext(readFileSync('src/vod-epg-identity.js','utf8'),ctx);
const match=ctx.window.DC4IEpgIdentity?.match;
assert.ok(match);
const e={title:'Example',year:'2026'},one={title:'Example',release_date:'2026-02-01',tmdb:{id:10,type:'movie'},vote_average:7.5,vote_count:200};
assert.equal(match(e,[one]).status,'candidate');
assert.equal(match(e,[one]).verified,false);
assert.equal(match(e,[one]).candidate.rating.source,'TMDB');
assert.equal(match(e,[one,{...one,tmdb:{id:11,type:'movie'}}]).status,'ambiguous');
assert.equal(match(e,[one,{...one,tmdb:{id:10,type:'tv'}}]).status,'ambiguous');
assert.equal(match({...e,year:''},[one]).status,'unmatched');
assert.equal(match(e,[{...one,release_date:'2025-01-01'}]).status,'unmatched');
assert.equal(match(e,[{...one,title:'Example 2'}]).status,'unmatched');
assert.equal(match(e,[one,one]).status,'candidate','duplicate same identity collapses');
assert.equal(match(e,[{...one,vote_average:0,vote_count:0}]).candidate.rating,null);
assert.ok(!JSON.stringify(match(e,[{...one,password:'secret',url:'https://private.invalid'}])).includes('secret'));
console.log('EPG_IDENTITY_PASS title+year candidates, ambiguity, no inferred verification, attributed ratings');
