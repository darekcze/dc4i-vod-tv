import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const root='build/dc4i-vodtv/';
const html=readFileSync(root+'index.html','utf8');
const search=readFileSync(root+'features/search.js','utf8');
const details=readFileSync(root+'features/details.js','utf8');
const app=readFileSync(root+'app.js','utf8');
const style=readFileSync(root+'vod-external-search.css','utf8');
assert.equal((html.match(/vod-external-search\.js/g)||[]).length,1);
assert.ok(html.indexOf('vod-external-search.js') < html.indexOf('features/details.js'));
assert.ok(html.includes('vod-external-search.css'));
assert.ok(search.includes('TV.vodExternalSearch.render'));
assert.ok(search.includes('Brak w wybranych serwisach'),'Search has precise no selected-VOD availability message');
assert.ok(search.includes('TV.svcFor'),'Search filters VOD availability by selected services');
assert.ok(search.indexOf('id="sres"') >= 0 && search.indexOf('id="sres"') < search.indexOf('id="syt"'),'Provider row is below VOD results');
assert.ok(!search.includes('Szukaj w YouTube'),'No single-provider legacy CTA');
assert.ok(details.includes('TV.vodExternalSearch.render'));
assert.ok(details.includes('class="dexternal"'),'Details show common search row below VOD section');
assert.equal((details.match(/TV\.vodPlayers\.open\('stremio'/g)||[]).length,0,'no duplicate Stremio CTA');
assert.equal((details.match(/TV\.vodHandoff\.youtubeSearch/g)||[]).length,0,'no duplicate YouTube CTA');
assert.ok(details.includes('Brak w wybranych serwisach'));
assert.ok(app.includes("target:'https://www.dc4i.com/labs'"));
assert.ok(app.includes("target:'https://lg.darc.dev/browse/'"));
assert.ok(html.includes('href="https://lg.darc.dev/browse/"'));
assert.ok(html.includes('href="https://www.dc4i.com/labs"'));
assert.ok(style.includes('.vx-engine'));
assert.ok(search.includes('externalButtons'),'Remote navigation includes the 5 provider buttons');
assert.ok(details.includes("querySelectorAll('.dexternal .f')"),'Remote navigation includes detail provider buttons');
console.log('UNIFIED_SEARCH_VIEW_ASSERTIONS_PASS');
