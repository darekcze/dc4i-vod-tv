import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const html=readFileSync('build/dc4i-vodtv/index.html','utf8');
const css=readFileSync('build/dc4i-vodtv/dc4i.css','utf8');
const js=readFileSync('build/dc4i-vodtv/app.js','utf8');
const block=html.match(/<div id="qpanel".*?<\/section>[\s\S]*?<\/div><\/div>/)?.[0] || html.slice(html.indexOf('<div id="qpanel"'),html.indexOf('<div id="sdim"'));
const d=block.match(/<div class="dc4i-dedication">([\s\S]*?)<\/div>/)?.[1]||'';
assert.ok(d.includes('Ani i ukochanej rodziny'),'family dedication preserved');
assert.equal((d.match(/Bo gdzie Wy jesteście/g)||[]).length,1,'no repeated verse');
assert.equal((d.match(/DC4i Labs/g)||[]).length,0,'no duplicate brand in dedication');
assert.ok(css.includes('width: 900px') || css.includes('width:900px'),'wide panel required');
assert.ok(!css.includes('.dc4i-about {margin-top:auto'),'no bottom-pushed about area');
assert.match(css, /\.dc4i-dedication p\s*\{[^}]*font-size:22px/, '22px readable prose');
assert.ok(!block.includes('title="DC4i Labs"'),'remove duplicated DC4i Labs logo hint');
assert.ok(block.includes('class="dc4i-quick-links qrow"'),'separate focusable link row');
assert.ok(js.includes("all('#quick .qrow, #quick .dc4i-about-logo')"),'remote navigates quick links and app logo');
assert.ok(js.includes('window.DC4IVersions.refresh'),'latest version must call version comparator');
assert.ok(html.includes('<script src="vod-version-check.js"></script>'),'version-check module must be loaded');
assert.ok(js.includes('getClientRects().length'),'hidden controls excluded from keyboard navigation');
console.log('QUICK_PANEL_DESIGN_ASSERTIONS_PASS');
