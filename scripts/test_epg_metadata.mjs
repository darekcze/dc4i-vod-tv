import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const ctx={window:{},Date,Number,String,Array,atob,TextDecoder,Uint8Array};
vm.runInNewContext(readFileSync('src/vod-epg.js','utf8'),ctx);
const epg=ctx.window.DC4IEPG;
const base64=Buffer.from('KATSEYE: Wild Hearts','utf8').toString('base64');
const start=Date.parse('2026-10-25T09:00:00Z')/1000;
const end=start+60*60;
const channel={id:'48',title:'[PL] HBO 2 HD',type:'live',archive:1,archiveDays:2};
const raw={title:base64,start:'2026-10-25 11:00:00',end:'2026-10-25 12:00:00',start_timestamp:String(start),stop_timestamp:String(end),has_archive:1};
const event=epg.parse(raw,channel,Date.parse('2026-10-25T10:00:00Z'));
assert.equal(event.title,'KATSEYE: Wild Hearts');
assert.equal(event.state,'past');
assert.equal(event.archiveFlag,true);
assert.equal(event.time.start,start*1000);
assert.equal(event.duration,60);
assert.equal(event.channelId,'48');
assert.equal(event.startParam,'2026-10-25:11-00');
assert.equal(epg.parse(raw,channel,Date.parse('2026-10-25T09:30:00Z')).state,'now');
assert.equal(epg.parse(raw,channel,Date.parse('2026-10-25T08:30:00Z')).state,'future');
assert.equal(epg.parse({...raw,has_archive:0},channel,Date.parse('2026-10-25T10:00:00Z')).archiveFlag,false);
assert.equal(epg.matches('KATSEYE Wild Hearts','katseye'),true);
assert.equal(epg.matches('KATSEYE: Wild Hearts','wild hearts'),true);
assert.equal(epg.matches('Football Tonight','katseye'),false);
assert.equal(epg.parse({title:'',start_timestamp:'wrong',stop_timestamp:'none'},channel,0),null);
console.log('EPG_METADATA_TEST_PASS');
