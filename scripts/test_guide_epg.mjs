import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const w={};
vm.runInNewContext(readFileSync(new URL('../src/vod-guide-epg.js',import.meta.url),'utf8'),
 {window:w,Promise,Object,String,Array,Number,Date});
const adapter=w.DC4IGuideEpg;
assert.ok(adapter?.create);
let clock=10_000,started=[],pending=[],active=0,maxActive=0;
const load=(channel)=>new Promise((resolve,reject)=>{
  started.push(channel.accountId+':'+channel.id);
  active++;maxActive=Math.max(maxActive,active);
  pending.push({id:channel.id,resolve:x=>{active--;resolve({epg_listings:x});},reject:x=>{active--;reject(x);}});
});
const parse=(raw,channel)=>({title:raw.title,channelId:channel.id,time:{start:raw.start,end:raw.end}});
const cache=adapter.create(load,parse,{ttlMs:5000,now:()=>clock});
const A={id:'101',accountId:'a'},B={id:'102',accountId:'a'},A2={id:'101',accountId:'b'};
let p1=cache.get(A),p2=cache.get(A),p3=cache.get(B);
assert.equal(p1,p2,'same channel in-flight de-duplicated');
await Promise.resolve();await Promise.resolve();
assert.equal(started.length,1,'one provider request at a time');
pending[0].resolve([{title:'A',start:1,end:2}]);
assert.equal((await p1)[0].title,'A');
await Promise.resolve();await Promise.resolve();
assert.equal(started.length,2);
pending[1].resolve([{title:'B',start:3,end:4}]);
assert.equal((await p3)[0].channelId,'102');
assert.equal(maxActive,1,'max one concurrent provider EPG call');
assert.equal((await cache.get(A))[0].title,'A','within TTL from cache');
assert.equal(started.length,2);
clock+=5100;
const p4=cache.get(A);
await Promise.resolve();await Promise.resolve();
assert.equal(started.length,3,'expired cache reloads');
pending[2].resolve([{title:'A refreshed',start:3,end:4}]);
assert.equal((await p4)[0].title,'A refreshed');
const p5=cache.get(A2);
await Promise.resolve();await Promise.resolve();
assert.equal(started.length,4,'same stream different account must not share EPG');
pending[3].resolve([{title:'A other provider',start:3,end:4}]);
await p5;
const p6=cache.get({id:'103',accountId:'a'});
await Promise.resolve();await Promise.resolve();
pending[4].reject(Error('Xtream unavailable'));
await assert.rejects(p6,/Xtream unavailable/);
const p7=cache.get({id:'104',accountId:'a'});
await Promise.resolve();await Promise.resolve();
assert.equal(started.length,6,'failure must not poison queue');
pending[5].resolve([]);
assert.deepEqual(Array.from(await p7),[]);
assert.deepEqual(Array.from(await cache.get(null)),[],'null input is safe');
console.log('GUIDE_EPG_QUEUE_TEST_PASS');
