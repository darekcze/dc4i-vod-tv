import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import vm from 'node:vm';
const src='src/vod-recommendations.js';
const window={};
if(existsSync(src))vm.runInNewContext(readFileSync(src,'utf8'),{window,Number,String,Date,Math,Array,Object});
const engine=window.DC4IRecommender;
assert.ok(engine && engine.score && engine.rank && engine.record,'RECOMMENDER module and public API must exist');
const defaults=engine.defaults;
assert.equal(defaults.sciFiMin,6);
assert.equal(defaults.horrorMin,9);
assert.equal(defaults.otherMin,7);
assert.equal(defaults.favouriteGenre,'scifi');
const make=(id,rating,genres,extra={})=>({
 id,tmdb:{id,type:'movie'},title:'Title '+id,genre_ids:genres,vote_average:rating,
 popularity:20,vote_count:150,release_date:'2026-01-01',...extra
});
const now=new Date('2026-10-25T21:00:00+01:00').getTime();
const check=(item,prefs={})=>engine.score(item,{...defaults,...prefs},[],now);
assert.equal(check(make(1,5.9,[878])).eligible,false,'Sci-Fi below 6 rejected');
assert.equal(check(make(2,6,[878])).eligible,true,'Sci-Fi 6 accepted');
assert.equal(check(make(3,8.9,[27])).eligible,false,'Horror 8.9 rejected by hard 9 gate');
assert.equal(check(make(4,9,[27])).eligible,true,'Horror 9 eligible before disable toggle');
assert.equal(check(make(5,10,[27]),{hideHorror:true}).eligible,false,'Hide Horror overrides top rating');
assert.equal(check(make(6,6.9,[35])).eligible,false,'Other genre below minimum 7');
assert.equal(check(make(7,7,[35])).eligible,true);
assert.equal(check(make(8,0,[878])).eligible,false,'unrated excluded');
assert.equal(check(make(9,null,[878])).eligible,false,'null rating excluded');
assert.equal(check(make(10,9.5,[878]),{enabled:false}).eligible,false);
const romantic=make(11,8,[10749,10751]);
const evening=check(romantic).score;
const noon=engine.score(romantic,defaults,[],new Date('2026-10-25T13:00:00+01:00').getTime()).score;
assert.ok(evening>noon,'romantic/family content boosted in evening');
assert.ok(evening<=100 && evening>=0);
const scifi=make(12,7.5,[878]);
const other=make(13,7.5,[35]);
assert.ok(check(scifi).score>check(other).score,'favorite genre Sci-Fi boosted');
let history=[];
history=engine.record(history,scifi,'opened',now-3600000);
history=engine.record(history,make(15,8,[878]),'opened',now-1800000);
const learned=engine.score(make(16,8,[878]),defaults,history,now).score;
const unlearned=engine.score(make(16,8,[878]),{...defaults,learnHistory:false},history,now).score;
assert.ok(learned>unlearned,'genre signals based only on in-app opened events');
const opened=engine.score(scifi,{...defaults,hideOpened:true},history,now);
assert.equal(opened.eligible,false,'optional previously opened suppression');
assert.equal(history[0].action,'opened','opening is not a watched/completed action');
assert.ok(!history.some(x=>x.action==='watched'),'do not forge watch completion');
assert.equal(engine.rank([scifi,scifi,other,make(7,7,[35])],defaults,[],now).length,3,'deduplicate same TMDB identity');
const ranked=engine.rank([other,scifi,romantic],defaults,[],now);
assert.ok(ranked.every(r=>r.score<=100 && r.score>=0 && r.item && r.reason));
assert.ok(ranked[0].score>=ranked[1].score);
let capped=[];
for(let i=1;i<201;i++)capped=engine.record(capped,make(i,7,[35]),'opened',now+i);
assert.equal(capped.length,150,'bounded local history');
assert.equal(engine.rank([],defaults,[],now).length,0);
assert.equal(engine.rank([scifi],{...defaults,enabled:false},[],now).length,0);
console.log('RECOMMENDER_TDD_TEST_PASS',ranked.map(r=>({id:r.item.id,score:r.score,reason:r.reason})));
